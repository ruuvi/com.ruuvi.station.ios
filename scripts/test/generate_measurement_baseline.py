#!/usr/bin/env python3
"""Regenerate the test-only original measurement implementation for differential tests."""
import argparse
import hashlib
from pathlib import Path
import subprocess

REVISION = "f2c7357f7f141cfe99c155c5c9292af0817b5f73"
SOURCE = "Packages/RuuviService/Sources/RuuviServiceMeasurement/RuuviServiceMeasurementImpl.swift"
DESTINATION = "Apps/RuuviStation/Tests/Unit/AppBehavior/BaselineMeasurementService.swift"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    original = subprocess.check_output(["git", "show", f"{REVISION}:{SOURCE}"], cwd=root, text=True)
    # Rename symbols only so the original and migrated implementations can run in one test process.
    baseline = original.replace("RuuviServiceMeasurementImpl", "BaselineMeasurementService")
    for old, new in [("nbsp", "baselineNBSP"), ("stringValue", "baselineStringValue"),
                     ("formattedStringValue", "baselineFormattedStringValue")]:
        baseline = baseline.replace(old, new)
    baseline = baseline.replace(".round(to:", ".baselineRound(to:").replace("func round(to", "func baselineRound(to")
    header = (
        "// swiftlint:disable all\n"
        "// Generated by scripts/test/generate_measurement_baseline.py; do not hand-edit.\n"
        f"// Baseline revision: {REVISION}\n"
        f"// Original SHA-256: {hashlib.sha256(original.encode()).hexdigest()}\n"
        "// Only symbol names and the RuuviService import differ from the original implementation.\n"
        "// This file belongs only to the test target and is excluded from production coverage by target type.\n"
        "import RuuviService\n"
    )
    expected = header + baseline
    destination = root / DESTINATION
    if args.check:
        if destination.read_text() != expected:
            raise SystemExit("Measurement baseline differs from its pinned original source; regenerate it.")
        print("Measurement baseline matches the pinned original source.")
    else:
        destination.write_text(expected)


if __name__ == "__main__":
    main()
